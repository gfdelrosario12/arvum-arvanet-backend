-- 1. Device MQTT Credentials for Per-Device Authentication & Topic ACLs
CREATE TABLE IF NOT EXISTS device_mqtt_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id VARCHAR(64) NOT NULL UNIQUE,
    username VARCHAR(128) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    client_id VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE, REVOKED, SUSPENDED
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dev_mqtt_user ON device_mqtt_credentials(username);
CREATE INDEX IF NOT EXISTS idx_dev_mqtt_device ON device_mqtt_credentials(device_id);

