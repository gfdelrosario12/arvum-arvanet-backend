-- 4. Transactional Outbox for Event-Driven Notifications & AI Analysis Dispatch
CREATE TABLE IF NOT EXISTS telemetry_event_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    event_type VARCHAR(64) NOT NULL, -- TELEMETRY_RECEIVED, SENSOR_FAULT, THRESHOLD_BREACH, WATER_SURGE
    node_id VARCHAR(64) NOT NULL,
    field_id BIGINT,
    zone_id BIGINT,
    payload_json TEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING', -- PENDING, DISPATCHED, FAILED
    retry_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dispatched_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_outbox_status_created ON telemetry_event_outbox(status, created_at ASC);

-- 5. AI Telemetry Insights Table (Completely Decoupled, Read-Only Agronomic Advisories)
CREATE TABLE IF NOT EXISTS ai_telemetry_insights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insight_id VARCHAR(64) NOT NULL UNIQUE,
    field_id BIGINT NOT NULL DEFAULT 1,
    zone_id BIGINT,
    insight_type VARCHAR(64) NOT NULL, -- SENSOR_ANOMALY, SOIL_DRYING_TREND, WATER_SURGE, EVAPOTRANSPIRATION, DRIFT_DETECTED
    severity VARCHAR(32) NOT NULL DEFAULT 'INFO', -- INFO, WARNING, ADVISORY
    confidence DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    title VARCHAR(255) NOT NULL,
    summary TEXT NOT NULL,
    recommended_action TEXT,
    window_start_time TIMESTAMP NOT NULL,
    window_end_time TIMESTAMP NOT NULL,
    model_version VARCHAR(64) NOT NULL DEFAULT 'RULES-HEURISTIC-V1',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ai_insights_zone_time ON ai_telemetry_insights(zone_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ai_insights_type ON ai_telemetry_insights(insight_type);

